N = int(input("Введіть ціле число N (N > 1): "))

while N <= 1:
    print("N повинно бути більше 1")
    N = int(input("Введіть ціле число N ще раз (N > 1): "))

K = 0

while 5 ** K <= N:
    K += 1

print(f"Найменше ціле число K, при якому 5^K > {N}: K = {K}")
print(f"Перевірка: 5^{K} = {5**K} > {N}")
